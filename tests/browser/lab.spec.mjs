import { test, expect } from '@playwright/test';
test('3D, cases, sections, modes and geometry recalculate without errors',async({page},testInfo)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
  await expect(page.locator('canvas')).toHaveCount(1);await expect(page.locator('#scene-error')).toBeHidden();
  await expect(page.locator('#metrics')).toContainText('193,40');
  const initial=await page.locator('#metrics').innerText();
  // On mobile the input panel is below the analysis; controls remain reachable by scrolling.
  await page.getByRole('button',{name:'P3',exact:true}).click();
  await expect(page.locator('#condition-badge')).toContainText('P3');
  await expect(page.locator('#metrics')).not.toHaveText(initial);
  await page.locator('[name=t1]').fill('6');await page.locator('[name=t1]').blur();
  await expect(page.locator('#input-error')).toBeHidden();
  await page.getByRole('button',{name:'02 Torção'}).click();
  await expect(page.locator('#analysis-title')).toContainText('Torção');
  await page.locator('#station').fill('120');await page.locator('#station').dispatchEvent('input');
  await expect(page.locator('#section-label')).toHaveText('x = 3,00 m');
  await page.getByRole('button',{name:'04 Flambagem'}).click();
  await page.getByRole('button',{name:'Abrir caixa'}).click();
  await expect(page.locator('#open-box')).toHaveAttribute('aria-pressed','true');
  await page.getByRole('button',{name:'Com reforços',exact:true}).click();
  await expect(page.locator('#reinforced')).toHaveText('Sem reforços');
  await page.locator('#field').selectOption('sigma');
  await expect(page.locator('#legend-title')).toHaveText('σ · MPa');
  await page.locator('#deformation').fill('0');await page.locator('#deformation').dispatchEvent('input');
  await expect(page.locator('#scale-value')).toHaveText('0×');
  await page.locator('#home').click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath('lab.png'),fullPage:true});
  await testInfo.attach('lab',{path:testInfo.outputPath('lab.png'),contentType:'image/png'});
  expect(errors).toEqual([]);
});
test('invalid values block exports; JSON roundtrip and CSV downloads work',async({page})=>{
  await page.goto('/');await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
  await page.locator('[name=height]').fill('0');await page.locator('[name=height]').blur();
  await expect(page.locator('#export')).toBeDisabled();await expect(page.locator('#input-error')).toBeVisible();
  await page.getByRole('button',{name:'Restaurar'}).click();await expect(page.locator('#export')).toBeEnabled();
  await page.locator('#export').click();
  const csvPromise=page.waitForEvent('download');await page.locator('#csv').click();const csv=await csvPromise;expect(csv.suggestedFilename()).toBe('estruturas-resultados.csv');
  const jsonPromise=page.waitForEvent('download');await page.locator('#json').click();const json=await jsonPromise;
  const path=await json.path();const {readFile}=await import('node:fs/promises');const data=JSON.parse(await readFile(path,'utf8'));
  expect(data.parameters.span).toBe(12);expect(data.results.x).toHaveLength(241);
  await page.getByRole('button',{name:'Fechar',exact:true}).click();
  data.parameters.span=14;
  await page.locator('#file').setInputFiles({name:'scenario.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(data))});
  await expect(page.locator('[name=span]')).toHaveValue('14');await expect(page.locator('#input-error')).toBeHidden();
  await page.locator('#file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"schema":"wrong"}')});
  await expect(page.locator('#input-error')).toBeVisible();await expect(page.locator('[name=span]')).toHaveValue('14');
});
